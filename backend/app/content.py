def parse_items(text):
    return [(1 if line[0]=="+" else -1,line[1:]) for line in text.strip().splitlines() if line.strip()]

def make_bank():
    basic,extra,domains=[],[],[]
    for dim,text in CORE.items():
        items=parse_items(text)
        assert len(items)==30,(dim,len(items))
        split=24 if dim=="JP" else 25
        for i,(direction,wording) in enumerate(items):
            q={"id":f"{dim.lower()}-{i+1:02}","text":wording,"dimension":dim,"direction":direction,"section":"base" if i<split else "personality","facet":dim,"na":False}
            (basic if i<split else extra).append(q)
    random.Random(20261016).shuffle(basic)
    random.Random(1016).shuffle(extra)
    for key,data in FACETS.items():
        items=parse_items(data['items']);assert len(items)==10,(key,len(items))
